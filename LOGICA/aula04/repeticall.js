// Declarar uma variável chamada contador que reebe um valor númerico
let contador = 0

// Enquanto contador for menor ou igual a 10, repita
while (contador <= 10) {
    console.log("OLHA A HORA DO CAFÉ");
    console.log("VENHA TOMAR SEU CAFÉ!");
    console.log("CAFÉ DA MANHÃ, CAFÉ DA TARDE! NÃO IMPORTA!");
    console.log("VENHA TOMAR O SEU CAFÉ!!!");

    // Adicionar ++ após o nome de uma variável faz com que seja adicionado 1 ao seu valor
    contador++
    console.log(contador);
}
